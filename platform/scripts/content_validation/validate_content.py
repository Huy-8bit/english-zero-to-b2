"""Validate how the curriculum Markdown is imported into the learning platform.

Usage (from platform/):  backend/.venv/bin/python scripts/content_validation/validate_content.py [--json]

Reports, per unit: steps, quiz items, items with an answer key, auto-gradable
items, and problems:
- no-steps: the document produced no learning step
- no-answer: an exercise item has no matching entry in the answer file
- mc-unresolved: a closed question whose correct option could not be read
- exercise-section-without-items: a heading that looks like an exercise produced
  no interactive item (content is still shown as a slide, but not graded)
Writes platform/CONTENT-IMPORT-REPORT.md. Exit code 1 if a unit has no steps.
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter
from pathlib import Path

PLATFORM = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PLATFORM / "backend"))

from app.config import CONTENT_ROOT  # noqa: E402
from app.content.builder import EXERCISE_HEADING  # noqa: E402
from app.content.md import fold, split_by_heading, strip_md  # noqa: E402
from app.content.store import ContentStore  # noqa: E402


def exercise_sections_without_items(store: ContentStore, built) -> list[str]:
    if built.unit.kind == "grammar":
        return []
    md = (store.root / built.unit.path).read_text(encoding="utf-8")
    quiz_titles = {fold(st["title"]) for st in built.steps if st["type"] == "quiz"}
    missing = []
    _, secs = split_by_heading(md, 2)
    for sec in secs:
        _, subs = split_by_heading(sec.body, 3)
        for sub in subs or [sec]:
            title = strip_md(sub.title)
            full = f"{strip_md(sec.title)} — {title}" if subs else title
            if not EXERCISE_HEADING.search(fold(title + " " + (sec.title if subs else ""))):
                continue
            has_task_text = bool(re.search(r"^\s*(\*\*\w+\.|\d+\.\s)", sub.body, re.M))
            if has_task_text and fold(full) not in quiz_titles:
                missing.append(full)
    return missing


def main() -> int:
    store = ContentStore(CONTENT_ROOT, reload_seconds=0)
    rows, problems = [], Counter()
    details: dict[str, list[str]] = {}
    totals = Counter()
    for built in store.all_built():
        u = built.unit
        st = built.stats
        warn = list(built.warnings)
        warn += [f"exercise-section-without-items {t}" for t in exercise_sections_without_items(store, built)]
        for w in warn:
            problems[w.split()[0]] += 1
        if warn:
            details[u.id] = warn
        rows.append((u.id, u.kind, u.level or "", st["steps"], st["items"], st["keyed_items"], st["auto_items"], len(warn)))
        for k in ("steps", "items", "keyed_items", "auto_items"):
            totals[k] += st[k]
        totals[f"kind:{u.kind}"] += 1
    cards = store.cards()
    report = {
        "content_root": str(CONTENT_ROOT),
        "units": len(rows),
        "reference_docs": len(store.refs),
        "vocabulary_cards": len(cards),
        "totals": dict(totals),
        "problems": dict(problems),
        "details": details,
    }
    if "--json" in sys.argv:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    out = [
        "# Content Import Report",
        "",
        "Generated by `scripts/content_validation/validate_content.py`. Do not edit by hand.",
        "",
        f"- Content root: `{CONTENT_ROOT.name}/`",
        f"- Learning units: **{len(rows)}** · Reference documents (Reference Mode only): **{len(store.refs)}**",
        f"- Learning steps: **{totals['steps']}** · Quiz items: **{totals['items']}** "
        f"(with answer key: {totals['keyed_items']}, auto-gradable closed questions: {totals['auto_items']})",
        f"- Vocabulary flashcards: **{len(cards)}**",
        "",
        "Items without an answer key are speaking/writing tasks whose source gives only guidance; they use self-assessment.",
        "",
        "## Problems",
        "",
    ]
    if problems:
        out += [f"- `{k}`: {v}" for k, v in sorted(problems.items())]
    else:
        out.append("- None")
    out += ["", "## Units", "", "| ID | Kind | Level | Steps | Items | Keyed | Auto | Problems |", "|---|---|---|---:|---:|---:|---:|---:|"]
    out += [f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} | {r[6]} | {r[7]} |" for r in rows]
    if details:
        out += ["", "## Problem details", ""]
        for uid, warns in details.items():
            out.append(f"- **{uid}**: " + "; ".join(f"`{w}`" for w in warns[:40]) + (" …" if len(warns) > 40 else ""))
    (PLATFORM / "CONTENT-IMPORT-REPORT.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"units={len(rows)} steps={totals['steps']} items={totals['items']} keyed={totals['keyed_items']} "
          f"auto={totals['auto_items']} cards={len(cards)} problems={dict(problems)}")
    return 1 if problems.get("no-steps") else 0


if __name__ == "__main__":
    raise SystemExit(main())
